/**
 * Trigger detection, stop-command detection, loop-prevention, and
 * WhatsApp/Baileys message text extraction for Fathy AI (فتحي).
 */

/** Invisible zero-width marker appended to Fathy's outgoing replies to prevent self-trigger loops even across restarts. */
export const FATHY_SIGNATURE_MARKER = "\u200B\u200C";

/**
 * Normalize Arabic and Latin text for resilient trigger matching:
 * - Lowercase
 * - Strip Arabic tashkeel / diacritics & tatweel
 * - Normalize Alef (أ إ آ -> ا), Yaa/Alef Maksura (ى -> ي), Taa Marbuta (ة -> ه)
 * - Collapse repeated letters (e.g. "فتحىىى" -> "فتحي", "fathyyy" -> "fathy")
 */
export function normalizeForTrigger(input) {
  if (!input || typeof input !== "string") return "";
  return input
    .toLowerCase()
    // Strip zero-width characters & tatweel
    .replace(/[\u200B-\u200F\uFEFF\u0640]/g, "")
    // Strip Arabic diacritics (tashkeel)
    .replace(/[\u064B-\u065F\u0670]/g, "")
    // Normalize Arabic letter variants
    .replace(/[أإآٱ]/g, "ا")
    .replace(/ى/g, "ي")
    .replace(/ة/g, "ه")
    // Collapse elongated letters: 3+ in English (preserves "off", "sleep") and 2+ in Arabic ("فتحىى" -> "فتحي")
    .replace(/([a-z])\1{2,}/g, "$1")
    .replace(/([\u0621-\u064A])\1+/g, "$1")
    .trim();
}

/**
 * Check whether a message calls / invokes Fathy (فتحي / فتحى / fathy / FATHY).
 */
export function isFathyTrigger(text) {
  const norm = normalizeForTrigger(text);
  if (!norm) return false;

  // English variants: fathy, fathi, fathey (word-bounded, optionally preceded by @)
  if (/(?:^|[\s@#.,!?:;'"()[\]{}\-_/\\])fath(?:y|i|ey)(?:$|[\s.,!?:;'"()[\]{}\-_/\\])/i.test(norm)) {
    return true;
  }

  // Arabic variants after normalization ("فتحي", "يا فتحي", "يافتحي", "وفتحي", "لفتحي", "الفتحي")
  // Note: Arabic letters don't work with ASCII \b, so we use explicit non-letter boundaries.
  if (/(?:^|[^\u0621-\u064Aa-z0-9])(?:يا\s*|يا|و|ل|ب|ف)?فتحي(?:$|[^\u0621-\u064Aa-z0-9])/i.test(norm)) {
    return true;
  }

  return false;
}

/**
 * Check whether the user is asking Fathy to stop / sleep in this chat.
 */
export function isFathyStopCommand(text) {
  const norm = normalizeForTrigger(text);
  if (!norm) return false;

  const stopPatterns = [
    /(?:خلاص|كفايه|اسكت|اقفل|قفل|نام|وقف|توقف|باي|مع السلامه|شكرا|تسلم)\s*(?:يا\s*)?فتحي/,
    /(?:يا\s*)?فتحي\s*(?:خلاص|كفايه|اسكت|اقفل|قفل|نام|وقف|توقف|باي|اطلع)/,
    /\b(?:stop|mute|sleep|off|bye|quiet|shut up)\s+fath(?:y|i|ey)\b/i,
    /\bfath(?:y|i|ey)\s+(?:stop|mute|sleep|off|bye|quiet|pause)\b/i,
  ];

  return stopPatterns.some((re) => re.test(norm));
}

/**
 * Detect whether a message was generated by Fathy itself (to guarantee zero infinite loops).
 */
export function isFathyOwnMessage(text, messageId, sentMessageIds) {
  if (messageId && sentMessageIds && sentMessageIds.has(messageId)) {
    return true;
  }
  if (typeof text === "string") {
    if (text.includes(FATHY_SIGNATURE_MARKER)) return true;
    if (/^🤖\s*\*?فتحي/.test(text.trim())) return true;
  }
  return false;
}

/**
 * Unwrap nested WhatsApp/Baileys message envelopes (ephemeral, viewOnce, documentWithCaption).
 */
function unwrapMessageContainer(msg) {
  if (!msg || typeof msg !== "object") return null;
  if (msg.ephemeralMessage?.message) return unwrapMessageContainer(msg.ephemeralMessage.message);
  if (msg.viewOnceMessage?.message) return unwrapMessageContainer(msg.viewOnceMessage.message);
  if (msg.viewOnceMessageV2?.message) return unwrapMessageContainer(msg.viewOnceMessageV2.message);
  if (msg.viewOnceMessageV2Extension?.message) {
    return unwrapMessageContainer(msg.viewOnceMessageV2Extension.message);
  }
  if (msg.documentWithCaptionMessage?.message) {
    return unwrapMessageContainer(msg.documentWithCaptionMessage.message);
  }
  if (msg.editedMessage?.message?.protocolMessage?.editedMessage) {
    return unwrapMessageContainer(msg.editedMessage.message.protocolMessage.editedMessage);
  }
  return msg;
}

/**
 * Extract human-readable text + optional quoted message info from an Evolution API / Baileys message object.
 */
export function extractMessageDetails(rawRecord) {
  if (!rawRecord || typeof rawRecord !== "object") {
    return { text: "", quotedText: "", quotedIsFathy: false, mediaType: null };
  }

  const msg = unwrapMessageContainer(rawRecord.message);
  let text = "";
  let mediaType = null;
  let contextInfo = null;

  if (msg) {
    if (typeof msg.conversation === "string") {
      text = msg.conversation;
    } else if (msg.extendedTextMessage?.text) {
      text = msg.extendedTextMessage.text;
      contextInfo = msg.extendedTextMessage.contextInfo || null;
    } else if (msg.imageMessage) {
      mediaType = "image";
      contextInfo = msg.imageMessage.contextInfo || null;
      const cap = (msg.imageMessage.caption || "").trim();
      text = cap ? `[صورة] ${cap}` : "[صورة]";
    } else if (msg.videoMessage) {
      mediaType = "video";
      contextInfo = msg.videoMessage.contextInfo || null;
      const cap = (msg.videoMessage.caption || "").trim();
      text = cap ? `[فيديو] ${cap}` : "[فيديو]";
    } else if (msg.documentMessage) {
      mediaType = "document";
      contextInfo = msg.documentMessage.contextInfo || null;
      const fileName = msg.documentMessage.fileName || msg.documentMessage.title || "ملف";
      const cap = (msg.documentMessage.caption || "").trim();
      text = cap ? `[ملف: ${fileName}] ${cap}` : `[ملف: ${fileName}]`;
    } else if (msg.audioMessage) {
      mediaType = "audio";
      contextInfo = msg.audioMessage.contextInfo || null;
      text = msg.audioMessage.ptt ? "[رسالة صوتية]" : "[ملف صوتي]";
    } else if (msg.stickerMessage) {
      mediaType = "sticker";
      text = "[ملصق]";
    } else if (msg.locationMessage) {
      mediaType = "location";
      const name = msg.locationMessage.name || msg.locationMessage.address || "";
      text = name ? `[موقع جغرافي: ${name}]` : "[موقع جغرافي]";
    } else if (msg.contactMessage) {
      mediaType = "contact";
      text = `[جهة اتصال: ${msg.contactMessage.displayName || ""}]`;
    } else if (msg.buttonsResponseMessage?.selectedDisplayText) {
      text = msg.buttonsResponseMessage.selectedDisplayText;
    } else if (msg.listResponseMessage?.title) {
      text = msg.listResponseMessage.title;
    }
  }

  // Fallback to flat `text` property if Evolution returned one
  if (!text && typeof rawRecord.text === "string") {
    text = rawRecord.text;
  }

  // Check if message quotes / replies to an earlier message
  let quotedText = "";
  let quotedIsFathy = false;
  const quotedMsg =
    contextInfo?.quotedMessage || rawRecord.contextInfo?.quotedMessage || null;
  if (quotedMsg) {
    const inner = extractMessageDetails({ message: quotedMsg });
    quotedText = inner.text;
    if (isFathyOwnMessage(quotedText, contextInfo?.stanzaId, null)) {
      quotedIsFathy = true;
    }
  }

  return {
    text: (text || "").trim(),
    quotedText: (quotedText || "").trim(),
    quotedIsFathy,
    mediaType,
  };
}
